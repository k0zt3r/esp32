"""Embed the complete offline dashboard as a deterministic gzip asset."""
import gzip
from pathlib import Path

root = Path(__file__).resolve().parents[1] / "ThermoDashboard"
source = (root / "ui.html").read_bytes()
packed = gzip.compress(source, compresslevel=9, mtime=0)
rows = [", ".join(f"0x{byte:02x}" for byte in packed[i:i + 20]) for i in range(0, len(packed), 20)]
header = "#pragma once\n#include <Arduino.h>\n// Generated by tools/pack_dashboard.py from ui.html.\nconst uint8_t DASHBOARD_GZIP[] PROGMEM = {\n  "
header += ",\n  ".join(rows) + "\n};\nconstexpr size_t DASHBOARD_GZIP_LEN = sizeof(DASHBOARD_GZIP);\n"
(root / "dashboard_page.h").write_text(header, encoding="utf-8")
print(f"Dashboard: {len(source)} bytes HTML -> {len(packed)} bytes gzip")
